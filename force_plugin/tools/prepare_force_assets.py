#!/usr/bin/env python3
"""Validate and copy an authorized collection into a Force-local asset tree.

The trusted universal importer runs before copying. Only private package
manifests, RUN checkpoints, and verified transaction/schedule files are copied;
ROMs, firmware, EFE payloads, program dumps, and audio are never copied.
"""
from __future__ import annotations
import argparse, hashlib, json, shutil, subprocess, sys, tempfile
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
IMPORTER=ROOT/"tools/audio_validation/import_factory_effect_collection.py"

def sha(path:Path)->str:
    h=hashlib.sha256()
    with path.open("rb") as f:
        for b in iter(lambda:f.read(1<<20),b""):h.update(b)
    return h.hexdigest()

def safe_relative(root:Path,path:str)->tuple[Path,str]:
    p=Path(path).resolve(strict=True)
    try: rel=p.relative_to(root)
    except ValueError as e: raise RuntimeError("trusted importer emitted a path outside the source collection") from e
    if not p.is_file() or p.is_symlink():raise RuntimeError("package asset is not a regular file")
    return p,rel.as_posix()

def main()->int:
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("collection",type=Path,help="private validated-packages directory from the trusted importer workflow")
    ap.add_argument("output",type=Path,help="new local asset directory; keep it outside the repository and release archive")
    a=ap.parse_args(); source=a.collection.expanduser().resolve(strict=True); out=a.output.expanduser().resolve()
    if out==ROOT or ROOT in out.parents:raise ValueError("Force assets must be outside the repository")
    if out.exists():raise ValueError("output must not exist; refusing to overwrite user-local assets")
    with tempfile.TemporaryDirectory(prefix="trollfx-force-import-") as td:
        audit=Path(td)/"audit.json"
        p=subprocess.run([sys.executable,str(IMPORTER),str(source),"--output",str(audit)],text=True,capture_output=True)
        if p.returncode:raise RuntimeError("trusted importer rejected the collection: "+(p.stderr.strip() or p.stdout.strip()))
        result=json.loads(audit.read_text()); slots=result.get("slots",[])
        accepted=[x for x in slots if x.get("registry_eligible") and x.get("descriptor")]
        expected=list(range(1,51))
        if sorted(int(x["slot"]) for x in accepted)!=expected:
            raise RuntimeError(f"collection is not release-complete: trusted importer accepted {len(accepted)}/50 slots")
        out.mkdir(parents=True)
        rows=["TROLLFX_FORCE_ASSETS\t1"]
        copied=0;clock_gaps=[]
        for item in sorted(accepted,key=lambda x:int(x["slot"])):
            d=item["descriptor"]; manifest,manifest_rel=safe_relative(source,d["package_manifest_path"])
            pkgdir=manifest.parent
            checkpoint,checkpoint_rel=safe_relative(source,d["run_checkpoint_path"])
            schedule,schedule_rel=safe_relative(source,d["firmware_event_schedule_path"])
            doc=json.loads(manifest.read_text())
            clock_verified=bool(doc.get("clock_evidence",{}).get("verified_after_run",False))
            if not clock_verified:clock_gaps.append(int(d["slot"]))
            history,history_rel=safe_relative(source,str(pkgdir/doc["firmware_events"]))
            paths=[(manifest,manifest_rel),(checkpoint,checkpoint_rel),(history,history_rel),(schedule,schedule_rel)]
            for src,rel in paths:
                target=out/rel;target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,target)
                if sha(src)!=sha(target):raise RuntimeError("copied asset hash mismatch")
            name=str(d["factory_name"])
            if any(c in name for c in "\t\r\n") or len(name)>128:raise RuntimeError("factory name cannot be represented safely")
            rate=float(d["factory_reference_rate_hz"])
            row=[str(d["slot"]),name,str(d["active_program_words"]),str(d["end_word"]),d["program_sha256"],format(rate,".12g"),
                 manifest_rel,sha(manifest),checkpoint_rel,d["run_checkpoint_sha256"],history_rel,sha(history),
                 schedule_rel,d["firmware_event_schedule_sha256"],str(len(d["firmware_event_schedule"]))]
            rows.append("\t".join(row));copied+=1
        (out/"provider-index.tsv").write_text("\n".join(rows)+"\n")
        (out/"ASSET_IMPORT.txt").write_text(
            "Authorized local ES5510 factory assets. Generated by the strict universal importer.\n"
            "Contains package manifests, RUN checkpoints, firmware transaction history, and event schedules.\n"
            "Keep private. Do not redistribute or add to a public plugin archive.\n")
        print(json.dumps({"result":"PASS","eligible_slots":copied,"asset_directory":str(out),
                      "source":"trusted universal factory package importer","audio_or_factory_binaries_copied":False,
                      "clock_unverified_after_run_slots":clock_gaps},indent=2))
    return 0
if __name__=="__main__":
    try:raise SystemExit(main())
    except (OSError,RuntimeError,ValueError,KeyError,TypeError,json.JSONDecodeError) as e:
        print(f"prepare_force_assets: ERROR: {e}",file=sys.stderr);raise SystemExit(2)
